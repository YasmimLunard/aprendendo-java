public class Calculadora {
     
    public double somar(double a, double b){
      return a + b;
    }
    public double subtrair (double a, double b){
        return a - b;
    }
    public double multiplicar (double a, double b){
        return a * b;
    }
    public double divisao (double a, double b){
        return a / b;
    }
}
